#!/usr/bin/env node
/**
 * Turns the Central Bureau of Statistics locality file into the list the publish form
 * suggests from.
 *
 *   npm run cities:generate
 *
 * Generated and committed rather than fetched at runtime: the list of Israeli
 * localities changes a handful of times a decade, and a form field should not wait on
 * a request to tell somebody their own town exists.
 *
 * The source is `scripts/cbs-localities.xml` — the published קובץ הישובים, in
 * windows-1255, which is why it is decoded explicitly rather than read as UTF-8.
 *
 * ## Spelling
 *
 * `Listing.city` is compared exactly: a search for one spelling does not find the
 * other. Our listings came from yad2 and say `תל אביב יפו`, while the CBS writes
 * `תל אביב - יפו`, so writing the CBS spelling into new listings would quietly create a
 * second Tel Aviv that no search reaches. Where the two disagree, ours wins — the same
 * rule the search suggestions already follow.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
// Beside the script, not under `data/`, which the repo ignores — a generator whose
// input is not in the repo cannot be re-run by anybody else.
const SOURCE = path.join(here, 'cbs-localities.xml');
const TARGET = path.resolve(here, '../../client/src/data/cities.ts');

/**
 * Where our own spelling differs from the CBS one.
 *
 * Keyed by the CBS name. Short on purpose: it is only the places we already hold
 * listings in, because only those have a spelling of ours to disagree with. Add to it
 * when a city's listings and this list drift apart — the comparison that finds them is
 * `cityKey` on both sides.
 */
const OURS = {
  'תל אביב - יפו': 'תל אביב יפו',
  'יהוד-מונוסון': 'יהוד מונוסון',
};

function localityNames(xml) {
  const names = [];
  for (const [, row] of xml.matchAll(/<ROW>([\s\S]*?)<\/ROW>/g)) {
    const match = row.match(/<שם_ישוב>([\s\S]*?)<\/שם_ישוב>/);
    const name = match?.[1].trim();
    if (name) names.push(OURS[name] ?? name);
  }
  return names;
}

const xml = new TextDecoder('windows-1255').decode(readFileSync(SOURCE));
const names = [...new Set(localityNames(xml))].sort((a, b) => a.localeCompare(b, 'he'));

if (names.length < 1000) {
  // The file has had ~1,300 localities for years. A short list means the parse found
  // something other than what it was looking for, and writing it would silently shrink
  // the picker to whatever happened to match.
  throw new Error(`Only ${names.length} localities parsed — refusing to write.`);
}

writeFileSync(
  TARGET,
  `/**
 * Every locality in Israel, from the Central Bureau of Statistics list.
 *
 * Generated by \`server/scripts/generate-cities.mjs\` — do not edit by hand. Where our
 * own listings spell a city differently from the CBS, ours is what appears here, because
 * \`Listing.city\` is compared exactly and the other spelling would be a city no search
 * reaches.
 *
 * ${names.length} localities, sorted in Hebrew.
 */
export const ISRAELI_CITIES: readonly string[] = [
${names.map((name) => `  '${name.replace(/'/g, "\\'")}',`).join('\n')}
];
`,
  'utf8',
);

console.log(`Wrote ${names.length} localities to ${path.relative(process.cwd(), TARGET)}`);
