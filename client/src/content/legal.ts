/**
 * The text of the terms of use and the privacy policy.
 *
 * Kept as data rather than as markup so the two pages share one renderer, and so the
 * wording can be revised without touching a component.
 *
 * ⚠ Every `[[…]]` is a fact only the business knows — the registered name, the company
 * number, the address, the contact mailbox. They are deliberately loud: a document that
 * goes live still saying `[[שם החברה]]` is obviously unfinished, where a plausible
 * invented name would not be.
 *
 * This is a draft to start from and to give to a lawyer, not a compliance exercise. It
 * is written against Israeli law as it applies to a listings platform — the Privacy
 * Protection Law and its Amendment 13, section 30A of the Communications Law for direct
 * marketing, and the Real Estate Agents Law, which governs the agencies rather than us.
 */

export interface LegalSection {
  heading: string;
  /** Paragraphs and bullet lists, in the order they appear. */
  blocks: ({ type: 'p'; text: string } | { type: 'list'; items: string[] })[];
}

export interface LegalDocument {
  title: string;
  updated: string;
  intro: string;
  sections: LegalSection[];
}

